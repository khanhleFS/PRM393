"""Extract ONLY the repository's library fixtures into an additive SQL Server import.

Never execute the original data-mssql.sql on the deployed database: it resets wallets/users.
Staging IDs are mapped by slug to real identity IDs; re-running preserves existing rows.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = (root / 'src/main/resources/data-mssql.sql').read_text(encoding='utf-8-sig')

def statements(table):
    results = []
    for match in re.finditer(r'^INSERT INTO ' + table + r'\s*\(', source, re.M):
        index, quoted = match.start(), False
        while index < len(source):
            ch = source[index]
            if ch == "'":
                if quoted and index + 1 < len(source) and source[index + 1] == "'":
                    index += 2
                    continue
                quoted = not quoted
            if ch == ';' and not quoted:
                results.append(source[match.start():index + 1].replace('INSERT INTO ' + table, 'INSERT INTO #seed_' + table, 1))
                break
            index += 1
        else:
            raise ValueError('Unterminated insert: ' + table)
    if not results:
        raise ValueError('Missing fixtures: ' + table)
    return '\n'.join(results)

header = '''-- GENERATED by build-cloud-library-seed.py from repository fixtures.
-- Additive import: no deletes, no wallet changes, no fixed production identity IDs.
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;
CREATE TABLE #seed_categories (id uniqueidentifier, name nvarchar(100), slug nvarchar(120));
CREATE TABLE #seed_novels (id bigint IDENTITY(1,1), author_id uniqueidentifier, title nvarchar(255), slug nvarchar(300), description nvarchar(max), cover_image_url nvarchar(500), status nvarchar(255), view_count int, created_at datetimeoffset(6), updated_at datetimeoffset(6));
CREATE TABLE #seed_novel_categories (novel_id bigint, category_id uniqueidentifier);
CREATE TABLE #seed_chapters (novel_id bigint, chapter_number int, title nvarchar(255), slug nvarchar(300), content nvarchar(max), status nvarchar(255), coin_price int, view_count int, created_at datetimeoffset(6), updated_at datetimeoffset(6));
'''
footer = '''
DECLARE @AuthorId uniqueidentifier;
SELECT @AuthorId = id FROM users WHERE email = 'demo-author@luminovels.invalid';
IF @AuthorId IS NULL
BEGIN
    SET @AuthorId = NEWID();
    INSERT INTO users (id,role,username,email,password,phone,is_active,coin_balance,is_author,created_at,updated_at)
    VALUES (@AuthorId,'AUTHOR',N'Lumi Demo Author','demo-author@luminovels.invalid','!disabled-demo-account',CONVERT(varchar(36),@AuthorId),0,0,1,SYSUTCDATETIME(),SYSUTCDATETIME());
END;
IF NOT EXISTS (SELECT 1 FROM author_profiles WHERE user_id=@AuthorId)
    INSERT INTO author_profiles (id,user_id,pen_name,bio,author_coin_balance,total_novels,total_chapters,total_views,status,created_at,updated_at)
    VALUES (NEWID(),@AuthorId,N'Lumi Demo',N'Repository demo library',0,0,0,0,'APPROVED',SYSUTCDATETIME(),SYSUTCDATETIME());
INSERT INTO categories (id,name,slug)
SELECT NEWID(),s.name,s.slug FROM #seed_categories s WHERE NOT EXISTS (SELECT 1 FROM categories t WHERE t.slug=s.slug);
INSERT INTO novels (author_id,title,slug,description,cover_image_url,status,view_count,created_at,updated_at)
SELECT @AuthorId,s.title,s.slug,s.description,s.cover_image_url,s.status,s.view_count,s.created_at,s.updated_at
FROM #seed_novels s WHERE NOT EXISTS (SELECT 1 FROM novels t WHERE t.slug=s.slug);
INSERT INTO novel_categories (novel_id,category_id)
SELECT n.id,c.id FROM #seed_novel_categories s
JOIN #seed_novels sn ON sn.id=s.novel_id JOIN novels n ON n.slug=sn.slug
JOIN #seed_categories sc ON sc.id=s.category_id JOIN categories c ON c.slug=sc.slug
WHERE NOT EXISTS (SELECT 1 FROM novel_categories t WHERE t.novel_id=n.id AND t.category_id=c.id);
INSERT INTO chapters (novel_id,chapter_number,title,slug,content,status,coin_price,view_count,created_at,updated_at)
SELECT n.id,s.chapter_number,s.title,s.slug,s.content,s.status,s.coin_price,s.view_count,s.created_at,s.updated_at
FROM #seed_chapters s JOIN #seed_novels sn ON sn.id=s.novel_id JOIN novels n ON n.slug=sn.slug
WHERE NOT EXISTS (SELECT 1 FROM chapters t WHERE t.novel_id=n.id AND (t.chapter_number=s.chapter_number OR t.slug=s.slug));
UPDATE author_profiles SET total_novels=(SELECT COUNT_BIG(*) FROM novels WHERE author_id=@AuthorId),
total_chapters=(SELECT COUNT_BIG(*) FROM chapters c JOIN novels n ON n.id=c.novel_id WHERE n.author_id=@AuthorId)
WHERE user_id=@AuthorId;
COMMIT;
SELECT (SELECT COUNT(*) FROM novels) AS Novels, (SELECT COUNT(*) FROM chapters) AS Chapters,
       (SELECT COUNT(*) FROM categories) AS Categories;
'''
output = root / 'scripts/seed-cloud-library.sql'
sql = header + '\n'.join(statements(t) for t in ('categories', 'novels', 'novel_categories', 'chapters')) + footer
output.write_text('\n'.join(line.rstrip() for line in sql.splitlines()) + '\n', encoding='utf-8')
print('Generated additive library seed:', output.name)
